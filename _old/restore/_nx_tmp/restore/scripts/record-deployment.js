// after deploying, turns deployments/*.json into docs/DEPLOYMENT.md and flips the
// "not deployed yet" caveats in the README, submission index and demo notes.
//   node scripts/record-deployment.js --repo=https://github.com/you/nexusai --demo=https://...
// safe to run more than once.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DEP = path.join(ROOT, "deployments");

const EXPLORER = {
  sepolia: "https://sepolia.etherscan.io",
  baseSepolia: "https://sepolia.basescan.org",
  arbitrumSepolia: "https://sepolia.arbiscan.io",
  amoy: "https://amoy.polygonscan.com",
  hoodi: "https://hoodi.etherscan.io",
};
const LABEL = {
  sepolia: "Ethereum Sepolia",
  baseSepolia: "Base Sepolia",
  arbitrumSepolia: "Arbitrum Sepolia",
  amoy: "Polygon Amoy",
  hoodi: "Ethereum Hoodi",
};

const arg = (k) => {
  const hit = process.argv.find((a) => a.startsWith(`--${k}=`));
  return hit ? hit.slice(k.length + 3) : "";
};
const repoUrl = arg("repo");
const demoUrl = arg("demo");

function readJson(f) {
  return JSON.parse(fs.readFileSync(f, "utf8"));
}

function main() {
  if (!fs.existsSync(DEP)) {
    console.error("No deployments/ directory. Run scripts/deploy.js first.");
    process.exitCode = 1;
    return;
  }
  const files = fs.readdirSync(DEP).filter((f) => f.endsWith(".json"));
  const chains = files
    .filter((f) => !f.startsWith("public-demo-"))
    .map((f) => readJson(path.join(DEP, f)))
    .filter((d) => EXPLORER[d.network])
    .sort((a, b) => (a.role === "hub" ? -1 : 1) - (b.role === "hub" ? -1 : 1));
  const demos = files.filter((f) => f.startsWith("public-demo-")).map((f) => readJson(path.join(DEP, f)));

  if (chains.length === 0) {
    console.error("No public-network deployment records found in deployments/.");
    process.exitCode = 1;
    return;
  }

  // ---- docs/DEPLOYMENT.md
  let md = "# Deployed addresses\n\n";
  md += "Generated by `scripts/record-deployment.js` from the files in `deployments/`.\n\n";
  for (const d of chains) {
    md += `## ${LABEL[d.network]} (${d.role})\n\n`;
    md += "| Contract | Address |\n|---|---|\n";
    for (const [name, addr] of Object.entries(d.contracts)) {
      md += `| ${name} | [\`${addr}\`](${EXPLORER[d.network]}/address/${addr}) |\n`;
    }
    md += `\nDeployed ${d.deployedAt || "see the JSON"}.\n\n`;
  }
  for (const ev of demos) {
    md += `## Cross-chain run: ${LABEL[ev.source.network]} to ${LABEL[ev.destination.network]}\n\n`;
    md += `${ev.workflow}\n\n`;
    md += "| Step | Network | Transaction |\n|---|---|---|\n";
    for (const t of ev.transactions) {
      md += `| ${t.label} | ${LABEL[t.network]} | [\`${t.hash.slice(0, 18)}...\`](${t.explorer}) |\n`;
    }
    if (ev.destinationState) {
      md += `\nDestination state after the run: model active ${ev.destinationState.active}, `;
      md += `origin chain ${ev.destinationState.originChain}.\n`;
    }
    md += "\nThe adapter is operator-relayed for the demonstration. It is not production CCIP or LayerZero transport.\n\n";
  }
  if (repoUrl) md += `## Repository\n\n${repoUrl}\n\n`;
  if (demoUrl) md += `## Demo recording\n\n${demoUrl}\n\n`;
  fs.writeFileSync(path.join(ROOT, "docs", "DEPLOYMENT.md"), md);
  console.log("wrote docs/DEPLOYMENT.md");

  const nets = chains.map((d) => LABEL[d.network]).join(" and ");

  // ---- patch the caveats
  const patch = (file, pairs) => {
    const p = path.join(ROOT, file);
    let t = fs.readFileSync(p, "utf8");
    let changed = 0;
    for (const [from, to] of pairs) {
      if (t.includes(from)) { t = t.replace(from, to); changed++; }
    }
    fs.writeFileSync(p, t);
    console.log(`  ${file}: ${changed}/${pairs.length} section(s) updated`);
  };

  patch("README.md", [[
`Everything runs locally. I have not deployed to the public testnets, so there
are no addresses or explorer links yet. The cross-chain demo uses a mock router,
not a real bridge, and \`deploy.js\` refuses to put the mock on a public network.`,
`Deployed to ${nets}. Addresses and transaction links are in
\`docs/DEPLOYMENT.md\`. The bridge adapter is operator-relayed for the
demonstration, not production CCIP or LayerZero transport.${repoUrl ? `\n\nRepo: ${repoUrl}` : ""}${demoUrl ? `\nDemo: ${demoUrl}` : ""}`,
  ]]);

  patch("SUBMISSION_INDEX.md", [
    [`| Live multi-testnet demo | Not done. \`npm run demo:crosschain\` is a local two-stack run. Four public targets are configured but nothing is deployed |`,
     `| Live multi-testnet demo | Deployed to ${nets}. Addresses, transaction hashes and explorer links in \`docs/DEPLOYMENT.md\`${demoUrl ? `. Recording: ${demoUrl}` : ""} |`],
    [`| Portfolio repo | README with setup steps and screenshots (\`docs/screenshots/\`), CI, licence, diagrams, demo materials. Still needs the public GitHub URL |`,
     `| Portfolio repo | README with setup steps and screenshots (\`docs/screenshots/\`), CI, licence, diagrams, demo materials${repoUrl ? `. ${repoUrl}` : ""} |`],
    [`No public testnet deployment, so no addresses or explorer links. The bridge is a
mock router. The security review is mine, not independent. The ML corpus is
synthetic. Details in the README caveats.`,
     `The bridge adapter is operator-relayed, not production transport. The security
review is mine, not independent. The ML corpus is synthetic. Details in the
README caveats.`],
  ]);

  patch("demo/README.md", [[
`## What is missing

The assignment asks for a live demonstration on multiple testnets and a demo
link. Neither exists yet. Four networks are configured in \`scripts/config.js\` and
the deploy, verify and handoff scripts are written, but nothing has been
deployed, so there are no addresses, explorer links or recording. The demo above
is local.`,
`## Public testnet run

Deployed to ${nets}. Addresses and transaction links are in \`docs/DEPLOYMENT.md\`.${demoUrl ? `\n\nRecording: ${demoUrl}` : ""}`,
  ]]);

  console.log("\ndone. rebuild the PDFs with: node scripts/build-pdfs.js\n");
}

main();
